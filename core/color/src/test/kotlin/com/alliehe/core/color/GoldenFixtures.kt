package com.alliehe.core.color

import java.io.File

/**
 * Inputs shared with the native host test (`core/color-native/src/test/cpp/host_test.cpp`).
 * Both languages verify `core/color/golden/color.golden`, which is how Kotlin↔C++ parity is enforced.
 */
object GoldenFixtures {
    val SEEDS: List<Pair<Int, Float>> = BrandColors.PRESETS.map { it to 0f } + listOf(
        BrandColors.BRAND_SEED to 1f,
        0xFF4285F4.toInt() to 0.5f,
        0xFF808080.toInt() to 0f,
        0xFF000000.toInt() to 0f,
        0xFFFFFFFF.toInt() to 0f,
        0xFF00FFFF.toInt() to 0f,
    )

    /** Synthetic images, generated by the same formulas in host_test.cpp. */
    fun image(name: String): Triple<IntArray, Int, Int> = when (name) {
        "stripes" -> make(100, 100) { x, y ->
            val k = (x + y * 100) % 10
            when { k < 7 -> 0xFF1E88E5.toInt(); k < 9 -> 0xFFE53935.toInt(); else -> 0xFF808080.toInt() }
        }
        "gradient" -> make(200, 150) { x, y ->
            val r = x * 255 / 199
            val g = y * 255 / 149
            (0xFF shl 24) or (r shl 16) or (g shl 8) or 128
        }
        "ring" -> make(48, 48) { x, y ->
            val dx = x - 24; val dy = y - 24
            val d2 = dx * dx + dy * dy
            if (d2 in 200..400) 0xFF43A047.toInt() else 0x00000000
        }
        "gray" -> make(64, 64) { x, _ -> val v = 40 + x * 2; (0xFF shl 24) or (v shl 16) or (v shl 8) or v }
        else -> error(name)
    }

    val IMAGES = listOf("stripes", "gradient", "ring", "gray")

    private fun make(w: Int, h: Int, f: (Int, Int) -> Int): Triple<IntArray, Int, Int> {
        val px = IntArray(w * h)
        for (y in 0 until h) for (x in 0 until w) px[y * w + x] = f(x, y)
        return Triple(px, w, h)
    }

    val goldenFile: File get() = File("golden/color.golden").let { if (it.parentFile.exists()) it else File("core/color/golden/color.golden") }

    fun hex(v: Int) = "%08X".format(v)
}
